package com.payflow.wallet.dto;

import jakarta.validation.constraints.DecimalMax;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.Data;

import java.math.BigDecimal;

/**
 * The wallet to top up always comes from the JWT, never from the request body.
 */
@Data
public class TopUpRequest {
    @NotNull(message = "Amount is required")
    @DecimalMin(value = "0.01", message = "Amount must be at least 0.01")
    @DecimalMax(value = "10000.00", message = "A single top-up can be at most 10,000")
    @Digits(integer = 15, fraction = 2, message = "Amount can have at most 2 decimal places")
    private BigDecimal amount;

    /** Optional. Send one to make retries safe; generated by the server if missing. */
    @Size(max = 128, message = "Idempotency key must be at most 128 characters")
    private String idempotencyKey;
}
